const DropdownMenuSubTrigger = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.SubTrigger>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.SubTrigger> & {
    inset?: number;
  }
>(({ className, inset = 0, children, ...props }, ref) => (
  <DropdownMenuPrimitive.SubTrigger
    ref={ref}
    className={cn(
      "flex cursor-pointer items-center justify-between rounded-md px-2 py-1.5 text-sm outline-none focus:bg-accent data-[open]:bg-accent",
      inset > 0 && `pl-${inset * 4}`,
      className
    )}
    {...props}
  >
    {children}
    <span className="ml-auto h-3 w-3 rotate-0 transition-transform data-[open:state=open]:rotate-180">
      <ChevronRight className="h-3 w-3" />
    </span>
  </DropdownMenuPrimitive.SubTrigger>
));
